"""Step 3 of phase 1: put our numbers next to the paper's and write results/phase1_results.md.

Paper reference values for PTB-XL come from the paper's figure comparing PTB-XL with MIMIC
(figs/ptbxlvsmimic_1.pdf in the arXiv source). The paper prints no PTB-XL table, so the bar
heights were read from the vector PDF (bar rectangles vs. tick positions); precision is about
+/-0.003. The paper reports only cosine margin and Procrustes, only for TS-TXT and IMG-TXT,
on PTB-XL. It reports no PTB-XL CKA, mutual kNN, retrieval, or TS-IMG numbers.

Usage:
    python src/compare.py --emb <dir with results_*.json> --out results/phase1_results.md
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

PAPER_PTBXL = {  # config -> pair -> metric -> value (digitized, see module docstring)
    "A": {"ts-txt": {"cos_margin": 0.322, "procrustes": 1.221},
          "img-txt": {"cos_margin": 0.350, "procrustes": 1.222}},
    "D": {"ts-txt": {"cos_margin": 0.337, "procrustes": 1.220},
          "img-txt": {"cos_margin": 0.382, "procrustes": 1.141}},
}
PAPER_MIMIC = {  # same figure, for context only
    "A": {"ts-txt": {"cos_margin": 0.444, "procrustes": 1.009},
          "img-txt": {"cos_margin": 0.494, "procrustes": 0.950}},
    "D": {"ts-txt": {"cos_margin": 0.473, "procrustes": 0.956},
          "img-txt": {"cos_margin": 0.533, "procrustes": 0.870}},
}
# Paper Table 2, TS<->IMG retrieval on MIMIC (%), macro-avg of both directions. Context only.
PAPER_MIMIC_TSIMG_R = {"A": (31.31, 61.84, 73.62), "D": (20.33, 45.79, 58.69)}
CONFIG_NAMES = {"A": "DINOv2-B + Qwen3-Emb-0.6B + MOMENT-B",
                "D": "SigLIP2-B + Qwen3-Emb-0.6B + Chronos-B"}
METRICS = [("cos_margin", "Cos margin ↑"), ("procrustes", "Procrustes ↓"),
           ("cka_rbf", "CKA (RBF) ↑"), ("mutual_knn@5", "mKNN@5 ↑"),
           ("R@1", "R@1 ↑"), ("R@5", "R@5 ↑"), ("R@10", "R@10 ↑")]
PAIRS = ["ts-img", "ts-txt", "img-txt"]


def agg(runs, pair, metric):
    v = np.array([r["test"][pair][metric] for r in runs])
    return v.mean(), (v.std(ddof=1) if len(v) > 1 else 0.0)


def fmt(m, s, pct=False):
    k = 100 if pct else 1
    return f"{m * k:.2f} ± {s * k:.2f}" if pct else f"{m:.3f} ± {s:.3f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--emb", required=True)
    ap.add_argument("--out", default="results/phase1_results.md")
    args = ap.parse_args()
    emb = Path(args.emb)
    lines = ["# Phase 1 results (auto-generated by src/compare.py)", ""]
    for cfg in ("A", "D"):
        f = emb / f"results_{cfg}.json"
        if not f.exists():
            continue
        R = json.load(open(f))
        runs = R["runs"]
        fu = emb / f"results_{cfg}_untrained.json"
        U = json.load(open(fu))["runs"] if fu.exists() else None
        lines += [f"## Config {cfg}: {CONFIG_NAMES[cfg]}",
                  f"Lead {R['lead']}, device {R['device']}, seeds {[r['seed'] for r in runs]}, "
                  f"epochs run {[r['epochs_run'] for r in runs]}. Mean ± sd over seeds.", "",
                  "### Head-to-head with the paper (the only PTB-XL numbers it reports)", "",
                  "| Pair | Metric | Paper (PTB-XL, digitized) | Ours | Ours − paper |",
                  "|---|---|---|---|---|"]
        for pair in ("ts-txt", "img-txt"):
            for met, lab in METRICS[:2]:
                p = PAPER_PTBXL[cfg][pair][met]
                m, s = agg(runs, pair, met)
                lines.append(f"| {pair.upper()} | {lab} | {p:.3f} | {fmt(m, s)} | {m - p:+.3f} |")
        lines += ["", "### All metrics, all pairs (ours)", "",
                  "| Pair | " + " | ".join(l for _, l in METRICS) + " |",
                  "|---|" + "---|" * len(METRICS)]
        for pair in PAIRS:
            cells = [fmt(*agg(runs, pair, met), pct=met.startswith("R@")) for met, _ in METRICS]
            lines.append(f"| {pair.upper()} | " + " | ".join(cells) + " |")
        if U:
            lines += ["", "Untrained heads (random init, same seeds), as a floor:", "",
                      "| Pair | " + " | ".join(l for _, l in METRICS) + " |",
                      "|---|" + "---|" * len(METRICS)]
            for pair in PAIRS:
                cells = [fmt(*agg(U, pair, met), pct=met.startswith("R@")) for met, _ in METRICS]
                lines.append(f"| {pair.upper()} | " + " | ".join(cells) + " |")
        r = PAPER_MIMIC_TSIMG_R[cfg]
        lines += ["", f"Context: paper's TS↔IMG retrieval for this config on **MIMIC** "
                      f"(Table 2): R@1/5/10 = {r[0]}/{r[1]}/{r[2]} %. "
                      f"The paper reports no PTB-XL retrieval.", ""]
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
